"""Generate Windows executable metadata from the shared application version."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from version import __version__


def main():
    if not re.fullmatch(r'\d+\.\d+\.\d+', __version__):
        raise ValueError('Expected a stable major.minor.patch version')
    numeric = tuple(int(part) for part in __version__.split('.')) + (0,)
    source = f'''# UTF-8 — generated by tools/write_version.py
VSVersionInfo(
    ffi=FixedFileInfo(
        filevers={numeric}, prodvers={numeric},
        mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)
    ),
    kids=[
        StringFileInfo([
            StringTable('040904b0', [
                StringStruct('FileDescription', 'Harpie SSH Key Manager'),
                StringStruct('FileVersion', '{__version__}'),
                StringStruct('InternalName', 'Harpie'),
                StringStruct('OriginalFilename', 'Harpie.exe'),
                StringStruct('ProductName', 'Harpie'),
                StringStruct('ProductVersion', '{__version__}')
            ])
        ]),
        VarFileInfo([VarStruct('Translation', [1033, 1200])])
    ]
)
'''
    (ROOT / 'assets' / 'windows_version.txt').write_text(source, encoding='utf-8')
    print(__version__)


if __name__ == '__main__':
    main()
